# Dev tool: regenerates TrailPrint3D/assets/text_icons.js -- 2D outlines of
# the text icons in assets/other.blend (the 3D ones text_objects.appendTextIcon
# adds next to a text), drawn by the map generator's Backplate top view
# (assets/shape_extras.js). Re-run after changing an icon in other.blend:
#
#   blender --background --factory-startup -P generate_text_icons.py
#
# Each icon is seen from above: its upward-facing faces, merged into one
# outline (holes kept) in the icon's own local coordinates (mm at scale 1,
# origin = the point appendTextIcon places), y up.

import json
import os
import sys

import bpy  # type: ignore

REPO = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, REPO)
if "TrailPrint3D" not in bpy.context.preferences.addons:
    bpy.ops.preferences.addon_enable(module="TrailPrint3D")  # for its bundled Shapely

from shapely.geometry import Polygon  # noqa: E402
from shapely.ops import unary_union  # noqa: E402

BLEND = os.path.join(REPO, "TrailPrint3D", "assets", "other.blend")
OUT = os.path.join(REPO, "TrailPrint3D", "assets", "text_icons.js")
# The icons the Shape Extras text rows offer (props.py's titleIcon/iconTextN).
ICONS = ["cycling", "hiking", "running", "swimming", "skiing", "snowboarding", "kajak",
         "distance", "elevation", "time", "speed", "date"]


def _ring_path(coords):
    pts = list(coords)[:-1]
    return "M" + " L".join(f"{x:.3f} {y:.3f}" for x, y in pts) + " Z"


def _outline(obj):
    mesh = obj.data
    tris = []
    for poly in mesh.polygons:
        if poly.normal.z < 0.5:
            continue
        pts = [(mesh.vertices[i].co.x, mesh.vertices[i].co.y) for i in poly.vertices]
        p = Polygon(pts)
        if not p.is_valid:
            p = p.buffer(0)
        if not p.is_empty:
            tris.append(p)
    # A hair of growth closes slivers between faces, then removed again.
    shape = unary_union([t.buffer(1e-4) for t in tris]).buffer(-1e-4).simplify(0.005)
    parts = [shape] if shape.geom_type == "Polygon" else list(shape.geoms)
    d = " ".join(_ring_path(p.exterior.coords) + "".join(" " + _ring_path(r.coords) for r in p.interiors)
                 for p in parts if not p.is_empty)
    minx, miny, maxx, maxy = (
        min(v.co.x for v in mesh.vertices), min(v.co.y for v in mesh.vertices),
        max(v.co.x for v in mesh.vertices), max(v.co.y for v in mesh.vertices),
    )
    return {"d": d, "minx": round(minx, 3), "maxx": round(maxx, 3), "miny": round(miny, 3), "maxy": round(maxy, 3)}


with bpy.data.libraries.load(BLEND, link=False) as (src, dst):
    missing = [n for n in ICONS if n not in src.objects]
    if missing:
        raise SystemExit(f"other.blend is missing icons: {missing}")
    dst.objects = ICONS

shapes = {obj.name: _outline(obj) for obj in dst.objects}
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("// GENERATED by generate_text_icons.py from assets/other.blend -- do not edit.\n")
    f.write("// 2D top-view outlines of the text icons (mm, icon's own origin, y up),\n")
    f.write("// drawn by assets/shape_extras.js's Backplate top view.\n")
    f.write("var TP3D_TEXT_ICON_SHAPES = " + json.dumps(shapes, indent=1) + ";\n")
print(f"Wrote {len(shapes)} icons to {OUT} ({os.path.getsize(OUT)} bytes)")
